import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Tiny blurred placeholder (~16px wide WebP as a data URI) shown while the real image loads.
async function lqipOf(file) {
  const buf = await sharp(file).resize({ width: 16 }).webp({ quality: 30 }).toBuffer();
  return `data:image/webp;base64,${buf.toString('base64')}`;
}

const FRONTEND_ROOT = path.resolve(__dirname, '..');
const GALLERY_DIR = path.resolve(FRONTEND_ROOT, 'public/assets/gallery');
const OUT_FILE = path.resolve(FRONTEND_ROOT, 'src/data/gallery.js');
const META_FILE = path.resolve(FRONTEND_ROOT, 'src/data/gallery-meta.js');

const CATEGORIES = [
  { id: 'all', label: 'All' },
  { id: 'sculptures', label: 'Sculptures', folder: 'sculptures', prefix: 'sculptures' },
  { id: 'murals', label: 'Wall Murals', folder: 'murals', prefix: 'murals' },
  { id: 'fountains', label: 'Water Fountains', folder: 'fountains', prefix: 'fountains' },
  { id: 'grc', label: 'GRC Products', folder: 'grc', prefix: 'grc' },
  { id: 'planters', label: 'Planters', folder: 'planters', prefix: 'planters' },
  { id: 'other', label: 'Other', folder: 'other', prefix: 'other' },
];

function extractSeq(filename) {
  const match = filename.match(/-(\d+)\.webp$/);
  return match ? parseInt(match[1], 10) : 999999;
}

async function run() {
  console.log('--- Invent Fine Art Gallery Manifest Builder ---');
  console.log(`Scanning: ${GALLERY_DIR}`);

  const items = [];
  const categoryCounts = {};

  for (const cat of CATEGORIES) {
    if (cat.id === 'all') continue;
    const catDir = path.join(GALLERY_DIR, cat.folder);
    if (!fs.existsSync(catDir)) {
      console.warn(`Category directory does not exist: ${catDir}`);
      categoryCounts[cat.id] = 0;
      continue;
    }

    // Only match full images (not thumb)
    const files = fs
      .readdirSync(catDir)
      .filter(f => f.endsWith('.webp') && !f.includes('-thumb') && f.startsWith(cat.prefix));

    files.sort((a, b) => extractSeq(a) - extractSeq(b));
    categoryCounts[cat.id] = files.length;

    for (const file of files) {
      const fullPath = path.join(catDir, file);
      const thumbFile = file.replace(/\.webp$/, '-thumb.webp');
      const thumbPath = path.join(catDir, thumbFile);

      if (!fs.existsSync(thumbPath)) {
        console.warn(`Missing thumb for ${file}`);
      }

      const meta = await sharp(fullPath).metadata();
      const n = extractSeq(file);
      const id = path.parse(file).name;

      items.push({
        id,
        category: cat.id,
        n,
        thumb: `/assets/gallery/${cat.folder}/${thumbFile}`,
        full: `/assets/gallery/${cat.folder}/${file}`,
        w: meta.width || 1200,
        h: meta.height || 800,
        lqip: await lqipOf(thumbPath),
        alt: `${cat.label} artwork #${n} by Invent Fine Art`,
      });
    }
  }

  // Ensure output dir exists
  const outDir = path.dirname(OUT_FILE);
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const stamp = new Date().toISOString();
  // Light file (counts only) so Home/Footer never pull the full manifest into the entry bundle.
  const metaContent = `// GENERATED FILE — DO NOT EDIT DIRECTLY.
// Generated by scripts/build-manifest.mjs
// Last generated: ${stamp}

export const categoryCounts = ${JSON.stringify(categoryCounts, null, 2)};

export const totalWorksCount = ${items.length};
`;

  const fileContent = `// GENERATED FILE — DO NOT EDIT DIRECTLY.
// Generated by scripts/build-manifest.mjs
// Last generated: ${stamp}

export const galleryManifest = ${JSON.stringify(items, null, 2)};

export default galleryManifest;
`;

  fs.writeFileSync(META_FILE, metaContent, 'utf8');

  // Placeholders for the non-gallery images (hero, intro, services, about, category covers), keyed by public URL.
  const publicRoot = path.resolve(FRONTEND_ROOT, 'public');
  const staticDirs = ['assets/hero', 'assets/intro', 'assets/services', 'assets/about', 'assets/gallery/covers'];
  const staticMap = {};
  for (const dir of staticDirs) {
    const abs = path.join(publicRoot, dir);
    if (!fs.existsSync(abs)) continue;
    for (const file of fs.readdirSync(abs)) {
      if (!file.endsWith('.webp') || file.endsWith('-960.webp')) continue;
      staticMap[`/${dir}/${file}`] = await lqipOf(path.join(abs, file));
    }
  }
  const lqipContent = `// GENERATED FILE — DO NOT EDIT DIRECTLY.
// Generated by scripts/build-manifest.mjs
// Last generated: ${stamp}

export const lqip = ${JSON.stringify(staticMap, null, 2)};

export default lqip;
`;
  fs.writeFileSync(path.resolve(FRONTEND_ROOT, 'src/data/lqip.js'), lqipContent, 'utf8');
  console.log(`Placeholders written for ${Object.keys(staticMap).length} static images`);
  fs.writeFileSync(OUT_FILE, fileContent, 'utf8');
  console.log(`Manifest successfully written to ${OUT_FILE}`);
  console.log(`Total artworks indexed: ${items.length}`);
  console.log('Category breakdown:', categoryCounts);
}

run().catch((err) => {
  console.error('Fatal error building gallery manifest:', err);
  process.exit(1);
});
