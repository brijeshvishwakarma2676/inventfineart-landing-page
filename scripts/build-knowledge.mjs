// Builds api/_lib/knowledge.generated.js from chatbot/knowledge/*.md and chatbot/prompts/*.md.
// The serverless function imports that one file, so the facts and prompts ship with it (nothing reaches the browser bundle).
// Runs automatically before `npm run build` (prebuild) and on demand with `npm run knowledge`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const KNOWLEDGE_DIR = path.join(root, 'chatbot/knowledge');
const PROMPTS_DIR = path.join(root, 'chatbot/prompts');
const EVALS_FILE = path.join(root, 'chatbot/evals/questions.json');
const OUT = path.join(root, 'api/_lib/knowledge.generated.js');
const MAX_CHARS = 30000; // keep the whole knowledge base comfortably inside the model's context

const fail = (msg) => {
  console.error(`knowledge build failed: ${msg}`);
  process.exit(1);
};

// Minimal front matter parser: --- key: value ---, with [a, b] arrays.
function parse(file, raw) {
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) fail(`${file}: missing front matter (--- id/title ---)`);
  const meta = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (!kv) continue;
    const v = kv[2].trim();
    meta[kv[1]] = v.startsWith('[') ? v.slice(1, -1).split(',').map((s) => s.trim()).filter(Boolean) : v;
  }
  if (!meta.id || !meta.title) fail(`${file}: front matter needs id and title`);
  return { meta, body: m[2].trim() };
}

const read = (dir) =>
  fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .sort()
    .map((f) => ({ file: f, ...parse(f, fs.readFileSync(path.join(dir, f), 'utf8')) }));

const knowledge = read(KNOWLEDGE_DIR);
const ids = new Set();
for (const k of knowledge) {
  if (ids.has(k.meta.id)) fail(`duplicate knowledge id "${k.meta.id}"`);
  ids.add(k.meta.id);
  if (/\b(TODO|TBD|FIXME)\b/.test(k.body)) fail(`${k.file}: contains TODO/TBD/FIXME; resolve it or remove the line`);
}

const prompts = Object.fromEntries(read(PROMPTS_DIR).map((p) => [p.meta.id, p.body]));
if (!prompts.system || !prompts.system.includes('{{KNOWLEDGE}}')) fail('prompts/system.md must exist and contain {{KNOWLEDGE}}');

JSON.parse(fs.readFileSync(EVALS_FILE, 'utf8')); // validates the eval file

const knowledgeText = knowledge.map((k) => `## ${k.meta.title}\n\n${k.body.replace(/^# .*\n+/, '')}`).join('\n\n---\n\n');
if (knowledgeText.length > MAX_CHARS) fail(`knowledge is ${knowledgeText.length} chars (limit ${MAX_CHARS}); trim it`);

const items = knowledge.map((k) => ({ id: k.meta.id, title: k.meta.title, tags: k.meta.tags || [], source: k.meta.source || '', text: k.body }));
const out = `// GENERATED FILE — DO NOT EDIT. Edit chatbot/knowledge/*.md or chatbot/prompts/*.md, then run \`npm run knowledge\`.
// Generated by scripts/build-knowledge.mjs

export const knowledge = ${JSON.stringify(items, null, 2)};

export const knowledgeText = ${JSON.stringify(knowledgeText)};

export const prompts = ${JSON.stringify(prompts, null, 2)};

export const knowledgeMeta = ${JSON.stringify({ files: knowledge.length, chars: knowledgeText.length, approxTokens: Math.round(knowledgeText.length / 4) })};
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, 'utf8');
console.log(`knowledge: ${knowledge.length} files, ${knowledgeText.length} chars (~${Math.round(knowledgeText.length / 4)} tokens) -> api/_lib/knowledge.generated.js`);
